// Generates first-party brand raster assets from the APPROVED Logo 2
// (transparent variants extracted from brand-source/originals/logo2.jpg):
//   public/favicon.svg          (transparent dark mark, embedded raster)
//   public/brand/icon-180.png   (apple-touch-icon: navy square + light mark)
//   public/brand/brand-icon-512.png  (navy square + light mark)
//   public/brand/og-default-2026-10.png (social sharing card, real self-hosted
//     fonts). The filename is deliberately date-versioned: link-preview caches
//     (iMessage, Facebook, LinkedIn, X) key on the image URL, so a branding or
//     copy change must publish at a NEW filename to bust those caches. Bump
//     the suffix here and in src/components/BaseHead.astro together.
// Usage: node scripts/generate-brand-images.mjs  (requires: npm i -D playwright)
// The extracted logo variants are regenerated by the documented extraction
// process (see docs/IMAGE-GUIDE.md and brand-source/); this script only
// composes display assets from them.
import { createRequire } from 'node:module';
const require = createRequire('C:/Websites/Sunshine-Climate-Solutions/scripts/generate-review-qr.mjs');
const sharp = require('sharp');
import { chromium } from 'playwright';
import fs from 'node:fs';
import path from 'node:path';

const OUT_DIR = path.join('public', 'brand');
fs.mkdirSync(OUT_DIR, { recursive: true });

const b64 = (file) => fs.readFileSync(file).toString('base64');
const lightFull = 'brand-source/logo-light-full.png';
const darkFull = 'brand-source/logo-dark-full.png';

// 1. favicon.svg — transparent dark mark (navy letters + gold stripe), embedded
//    raster for faithful reproduction.
const faviconPng = await sharp(darkFull).resize({ height: 64 }).png({ compressionLevel: 9, palette: true, quality: 95 }).toBuffer();
const fm = await sharp(faviconPng).metadata();
fs.writeFileSync(
  'public/favicon.svg',
  `<svg xmlns="http://www.w3.org/2000/svg" width="${fm.width}" height="${fm.height}" viewBox="0 0 ${fm.width} ${fm.height}"><image width="${fm.width}" height="${fm.height}" href="data:image/png;base64,${faviconPng.toString('base64')}"/></svg>`,
);
console.log(`favicon.svg written (${Math.round(fs.statSync('public/favicon.svg').size / 1024)} KB, ${fm.width}x${fm.height})`);

// 1b. Search-engine favicon set — static PNG + ICO (Google's documented
//     favicon formats), built from the AUTHENTIC dark mark on a white square
//     with padding. Stable public URLs: /favicon.ico, /favicon-48.png,
//     /favicon-96.png, /brand/icon-192.png.
const squareIcon = async (size) => {
  const inner = Math.round(size * 0.72);
  const mark = await sharp(darkFull).resize({ width: inner, height: inner, fit: 'inside' }).toBuffer();
  const m = await sharp(mark).metadata();
  return sharp({ create: { width: size, height: size, channels: 4, background: '#ffffff' } })
    .composite([{ input: mark, left: Math.round((size - m.width) / 2), top: Math.round((size - m.height) / 2) }])
    .png({ compressionLevel: 9 })
    .toBuffer();
};
const png16 = await squareIcon(16);
const png32 = await squareIcon(32);
const png48 = await squareIcon(48);
const png96 = await squareIcon(96);
const png192 = await squareIcon(192);
fs.writeFileSync('public/favicon-48.png', png48);
fs.writeFileSync('public/favicon-96.png', png96);
fs.writeFileSync('public/brand/icon-192.png', png192);
// ICO container with PNG-embedded entries (16, 32, 48) — dependency-free.
{
  const entries = [[16, png16], [32, png32], [48, png48]];
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);
  let offset = 6 + entries.length * 16;
  const dirs = [];
  for (const [size, buf] of entries) {
    const d = Buffer.alloc(16);
    d.writeUInt8(size === 256 ? 0 : size, 0);
    d.writeUInt8(size === 256 ? 0 : size, 1);
    d.writeUInt8(0, 2);
    d.writeUInt8(0, 3);
    d.writeUInt16LE(1, 4);
    d.writeUInt16LE(32, 6);
    d.writeUInt32LE(buf.length, 8);
    d.writeUInt32LE(offset, 12);
    dirs.push(d);
    offset += buf.length;
  }
  fs.writeFileSync('public/favicon.ico', Buffer.concat([header, ...dirs, ...entries.map(([, b]) => b)]));
}
for (const f of ['public/favicon.ico', 'public/favicon-48.png', 'public/favicon-96.png', 'public/brand/icon-192.png']) {
  console.log(`${f} written (${Math.round(fs.statSync(f).size / 1024)} KB)`);
}

const browser = await chromium.launch();
try {
  const lightDataUrl = `data:image/png;base64,${b64(lightFull)}`;

  // 2. Square icons — navy background + light mark centered (62% width).
  for (const size of [180, 512]) {
    const context = await browser.newContext({
      viewport: { width: size, height: size },
      deviceScaleFactor: 1,
    });
    const page = await context.newPage();
    const inset = Math.round(size * 0.19);
    await page.setContent(
      `<!doctype html><html><head><style>
        html,body{margin:0;padding:0;background:#10263d}
        img{position:absolute;left:50%;top:50%;transform:translate(-50%,-50%);width:${size - inset * 2}px;height:auto;display:block}
      </style></head><body><img src="${lightDataUrl}" alt=""></body></html>`,
    );
    await page.waitForTimeout(150);
    await page.screenshot({ path: path.join(OUT_DIR, `icon-${size}.png`) });
    await context.close();
    console.log(`icon-${size}.png written`);
  }

  // 3. Social sharing card 1200x630 — navy bg, light SCS mark, real fonts.
  const context = await browser.newContext({ viewport: { width: 1200, height: 630 }, deviceScaleFactor: 1 });
  const page = await context.newPage();
  const archivo = b64('public/fonts/archivo-var-latin.woff2');
  const publicSans = b64('public/fonts/publicsans-var-latin.woff2');
  await page.setContent(
    `<!doctype html><html><head><meta charset="utf-8"><style>
      @font-face{font-family:'Archivo';src:url(data:font/woff2;base64,${archivo}) format('woff2');font-weight:500 800;font-display:block}
      @font-face{font-family:'Public Sans';src:url(data:font/woff2;base64,${publicSans}) format('woff2');font-weight:400 700;font-display:block}
      html,body{margin:0;padding:0}
      body{width:1200px;height:630px;background:#10263d;color:#fff;font-family:'Public Sans',sans-serif;display:flex;align-items:center;overflow:hidden;position:relative}
      .wrap{padding:0 80px}
      .mark{width:330px;height:auto;display:block;margin:0 0 26px}
      h1{font-family:'Archivo',sans-serif;font-weight:800;font-size:78px;line-height:1.05;letter-spacing:-.02em;margin:0 0 22px}
      h1 span{color:#f4b631}
      .sub{font-size:28px;line-height:1.4;color:#c9d6e3;margin:0 0 30px;max-width:32ch}
      .phone{display:inline-block;background:#f4b631;color:#10263d;font-family:'Archivo',sans-serif;font-weight:800;font-size:34px;padding:18px 34px;border-radius:12px}
      .arc{position:absolute;right:-80px;top:-60px;width:520px;opacity:.35}
    </style></head><body>
      <svg class="arc" viewBox="0 0 400 400" fill="none" stroke="#f4b631" stroke-width="2">
        <circle cx="200" cy="200" r="150"></circle>
        <circle cx="200" cy="200" r="110" stroke-dasharray="4 14"></circle>
        <circle cx="200" cy="200" r="55"></circle>
      </svg>
      <div class="wrap">
        <img class="mark" src="${lightDataUrl}" alt="">
        <h1>HVAC Solutions<br />for <span>Every Problem</span></h1>
        <p class="sub">Owner-operated heating and cooling service for Tampa Bay homes and businesses.</p>
        <div class="phone">(727) 661-5200</div>
      </div>
    </body></html>`,
  );
  await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(OUT_DIR, 'og-default-2026-10.png') });
  await context.close();
  console.log('og-default-2026-10.png written');
} finally {
  await browser.close();
}

// Report
for (const f of ['icon-180.png', 'icon-512.png', 'og-default-2026-10.png']) {
  const m = await sharp(path.join(OUT_DIR, f)).metadata();
  console.log(`${f}: ${m.width}x${m.height} ${Math.round(fs.statSync(path.join(OUT_DIR, f)).size / 1024)} KB`);
}
