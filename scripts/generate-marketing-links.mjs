// Central UTM / campaign link generator and verifier.
//
// Reads src/config/marketing-links.ts (single source of truth) and produces:
//   docs/marketing/UTM-MASTER-LINKS.md
//   docs/marketing/UTM-MASTER-LINKS.csv
//   docs/marketing/WHERE-TO-PASTE-UTM-LINKS.md
//   public/marketing/qr/<name>.svg | <name>.png | <name>-print.png
//
// Every QR is decoded with an independent decoder (jsQR in Chromium) and must
// match the exact intended URL.
//
// Usage:
//   node scripts/generate-marketing-links.mjs          generate docs + missing QRs, verify all
//   node scripts/generate-marketing-links.mjs --qr     also regenerate every QR
//   node scripts/generate-marketing-links.mjs --check  verify only (no writes), fail on drift
import fs from 'node:fs';
import path from 'node:path';
import QRCode from 'qrcode';
import { chromium } from 'playwright';
import { marketingLinks, qrAssets, destinations, siteUrl } from '../src/config/marketing-links.ts';

const args = new Set(process.argv.slice(2));
const CHECK_ONLY = args.has('--check');
const REGENERATE_QR = args.has('--qr') || !CHECK_ONLY;

const DOC_DIR = path.join('docs', 'marketing');
const QR_DIR = path.join('public', 'marketing', 'qr');
const MASTER_MD = path.join(DOC_DIR, 'UTM-MASTER-LINKS.md');
const MASTER_CSV = path.join(DOC_DIR, 'UTM-MASTER-LINKS.csv');
const CHEAT_MD = path.join(DOC_DIR, 'WHERE-TO-PASTE-UTM-LINKS.md');

const QR_OPTS = { errorCorrectionLevel: 'H', margin: 4, color: { dark: '#10263d', light: '#ffffff' } };
const UTM_VALUE = /^[a-z0-9_]+$/;
const FORBIDDEN_MEDIA = new Set(['cpc', 'ppc', 'paid_search', 'display', 'cpm']);
const FORBIDDEN_SOURCES = new Set(['googleads', 'adwords']);

// ── Validation ───────────────────────────────────────────────────────────────
const problems = [];
const ids = new Map();
const tuples = new Map();
const byId = new Map(marketingLinks.map((link) => [link.id, link]));

for (const link of marketingLinks) {
  if (!UTM_VALUE.test(link.id)) problems.push(`id "${link.id}" must be lowercase snake_case`);
  if (ids.has(link.id)) problems.push(`duplicate link id "${link.id}"`);
  ids.set(link.id, true);

  for (const [key, value] of Object.entries(link.utm)) {
    if (!value) continue;
    if (!UTM_VALUE.test(value)) {
      problems.push(`${link.id}: utm_${key} "${value}" must be lowercase snake_case (no spaces/uppercase)`);
    }
    if (value.includes('@') || /\d{7,}/.test(value)) {
      problems.push(`${link.id}: utm_${key} "${value}" looks like PII (email/phone digits are forbidden)`);
    }
  }
  if (!Object.values(destinations).includes(link.path)) {
    problems.push(`${link.id}: destination "${link.path}" is not a known internal page`);
  }
  if (FORBIDDEN_MEDIA.has(link.utm.medium) || FORBIDDEN_SOURCES.has(link.utm.source)) {
    problems.push(
      `${link.id}: manual Google Ads UTMs are prohibited — Google Ads must use auto-tagging (gclid/gbraid/wbraid/gad_*)`,
    );
  }
  const tuple = [link.utm.source, link.utm.medium, link.utm.campaign, link.utm.content ?? '', link.path].join('|');
  if (tuples.has(tuple)) {
    problems.push(`duplicate campaign definition: "${tuples.get(tuple)}" and "${link.id}" both use ${tuple}`);
  }
  tuples.set(tuple, link.id);
}

for (const asset of qrAssets) {
  if (!UTM_VALUE.test(asset.id.replace(/-/g, '_'))) problems.push(`QR id "${asset.id}" must be lowercase`);
  if (!byId.has(asset.linkId)) problems.push(`QR "${asset.id}" references unknown link "${asset.linkId}"`);
}
if (new Set(qrAssets.map((a) => a.id)).size !== qrAssets.length) problems.push('duplicate QR asset ids');

if (problems.length) {
  console.error('REGISTRY VALIDATION FAILED:');
  for (const problem of problems) console.error(` - ${problem}`);
  process.exit(1);
}

// ── URL construction ─────────────────────────────────────────────────────────
const linkUrl = (link) => {
  const url = new URL(link.path, siteUrl);
  url.searchParams.set('utm_source', link.utm.source);
  url.searchParams.set('utm_medium', link.utm.medium);
  url.searchParams.set('utm_campaign', link.utm.campaign);
  if (link.utm.content) url.searchParams.set('utm_content', link.utm.content);
  return url.href;
};

const baseLinks = marketingLinks.filter((link) => link.manual && link.path === destinations.home);
const serviceLinks = marketingLinks.filter((link) => !baseLinks.includes(link));
const serviceQrLinks = new Set(
  qrAssets
    .map((asset) => byId.get(asset.linkId))
    .filter((link) => link && link.placement.startsWith('Print QR to'))
    .map((link) => link.id),
);

// ── Document generation ──────────────────────────────────────────────────────
const channelCount = new Set(marketingLinks.map((link) => link.channel)).size;
const manualCount = marketingLinks.filter((link) => link.manual).length;

const masterMd = `# UTM & campaign link master registry

**Generated by \`scripts/generate-marketing-links.mjs\` — do not edit by hand.**
Source of truth: \`src/config/marketing-links.ts\`. Site: ${siteUrl}.
GA4: \`G-EQ9CBESN23\` · GTM: \`GTM-MBGJ8SLD\`.

## Rules (non-negotiable)

- UTMs are for **inbound marketing links only**. Never add them to internal
  navigation, canonical URLs, sitemap entries, \`tel:\`/\`sms:\`/\`mailto:\` links, or the
  Google-review QR.
- The site never forces UTMs to persist while visitors browse — GA4 attributes the
  session from the landing page.
- Lowercase \`snake_case\` values only. Never include names, phone numbers, emails,
  addresses, ZIP codes or any other personal information.
- **Google Ads:** no manual UTMs. Use Google auto-tagging (gclid / gbraid / wbraid /
  gad_*) — the site preserves those parameters untouched.
- \`utm_term\` is not used (no paid-keyword campaigns). \`utm_id\` is reserved for durable
  campaign ids if a future paid campaign needs one; it is deliberately omitted from
  QR URLs to keep them short and easy to scan.

## Base channel links (${baseLinks.length})

| Channel | Placement | Final URL | Purpose |
| --- | --- | --- | --- |
${baseLinks
  .map(
    (link) =>
      `| ${link.channel} | ${link.placement} | ${linkUrl(link)} | ${link.purpose} |`,
  )
  .join('\n')}

## Service campaign links (${serviceLinks.length})

${Object.entries(destinations)
  .map(([key, destination]) => {
    const rows = serviceLinks.filter((link) => link.path === destination);
    if (!rows.length) return '';
    return `### ${destination}\n\n| Channel | Placement | Campaign | Content | Final URL |\n| --- | --- | --- | --- | --- |\n${rows
      .map(
        (link) =>
          `| ${link.channel} | ${link.placement} | ${link.utm.campaign} | ${link.utm.content ?? '—'} | ${linkUrl(link)} |`,
      )
      .join('\n')}\n`;
  })
  .filter(Boolean)
  .join('\n')}

## QR codes (${qrAssets.length})

Each QR encodes its exact tagged URL; all codes are decoded and verified against the
intended URL when generated. Files: \`public/marketing/qr/\`.

| Asset | Files | Encodes | Where it goes |
| --- | --- | --- | --- |
${qrAssets
  .map((asset) => {
    const link = byId.get(asset.linkId);
    return `| ${asset.label} | \`${asset.id}.svg\`, \`${asset.id}.png\`, \`${asset.id}-print.png\` | ${linkUrl(link)} | ${link.whereToPaste} |`;
  })
  .join('\n')}

## Google Ads — automatic tagging only

Do **not** create UTMs for Google Ads. Configure the final URL with no query string
and let Google append \`gclid\` (and \`gbraid\`/\`wbraid\` on iOS/consent-limited traffic).
The website is a static site with no server-side redirects, so these parameters are
preserved exactly as received; \`scripts/verify-attribution.mjs\` proves it.

## Meta / Instagram paid social — templates (no pixel installed)

Use dynamic ad-platform parameters where possible, and keep campaign/creative names
lowercase so the resolved values stay URL-safe:

- Facebook paid: \`?utm_source=facebook&utm_medium=paid_social&utm_campaign={{campaign.name}}&utm_content={{ad.name}}\`
- Instagram paid: \`?utm_source=instagram&utm_medium=paid_social&utm_campaign={{campaign.name}}&utm_content={{ad.name}}\`

Facebook and Instagram are kept as separate \`utm_source\` values so they can be
compared independently. No Meta Pixel or other advertising pixel is installed by
this system.

## Regenerating

\`\`\`
npm run marketing:links     # regenerate docs + missing QR codes, verify all
npm run marketing:qr        # force-regenerate every QR code
npm run marketing:verify    # validation + drift check + attribution tests
\`\`\`
`;

const csvEscape = (value) => {
  const text = String(value ?? '');
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
};

const csvHeader = [
  'Channel',
  'Campaign',
  'Placement',
  'Destination Page',
  'utm_source',
  'utm_medium',
  'utm_campaign',
  'utm_content',
  'Final URL',
  'Purpose',
  'Where Owner Must Paste It',
];
const csvRows = marketingLinks.map((link) =>
  [
    link.channel,
    link.campaign,
    link.placement,
    link.path,
    link.utm.source,
    link.utm.medium,
    link.utm.campaign,
    link.utm.content ?? '',
    linkUrl(link),
    link.purpose,
    link.whereToPaste,
  ]
    .map(csvEscape)
    .join(','),
);
const masterCsv = `${csvHeader.join(',')}\n${csvRows.join('\n')}\n`;

const pasteLinks = marketingLinks.filter(
  (link) => link.manual && !serviceQrLinks.has(link.id) && link.utm.medium !== 'qr',
);
const printQrLinks = marketingLinks.filter((link) => link.manual && link.utm.medium === 'qr');
const preparedLinks = marketingLinks.filter((link) => !link.manual);

const cheatMd = `# Where to paste each marketing link — owner cheat sheet

**Generated by \`scripts/generate-marketing-links.mjs\` — do not edit by hand.**
Every URL below is final and ready to copy. Nothing here changes the website.

## ✅ ALREADY IMPLEMENTED IN THE REPO (nothing to do)

- **${qrAssets.length} QR codes** in \`public/marketing/qr/\` — each encodes its own tagged URL
  and is decode-verified. Print the \`-print.png\` (3000px) or use the \`.svg\` for artwork.
- **${preparedLinks.length} prepared campaign links** (social posts, emails, SMS, GBP posts) —
  listed in \`UTM-MASTER-LINKS.md\`; copy the relevant one when you publish that post/email.
- The website itself: no UTMs are added to internal links, canonicals, the sitemap,
  \`tel:\`/\`sms:\`/\`mailto:\` links, or the Google-review QR.

## 📋 OWNER MANUAL STEP — paste these URLs into your platforms

${pasteLinks
  .map(
    (link, index) =>
      `${index + 1}. **${link.channel}** — ${link.placement}\n   Paste THIS URL:\n   \`${linkUrl(link)}\``,
  )
  .join('\n\n')}

## 🖨️ OWNER MANUAL STEP — print/place these QR assets

| Asset | Print file | Encodes | Place on |
| --- | --- | --- | --- |
${printQrLinks
  .map((link) => {
    const asset = qrAssets.find((candidate) => candidate.linkId === link.id);
    return `| ${asset?.label ?? link.channel} | \`public/marketing/qr/${asset?.id}.svg\` (or \`${asset?.id}-print.png\`) | ${linkUrl(link)} | ${link.whereToPaste} |`;
  })
  .join('\n')}

## ⚠️ Google Ads — do NOT use UTMs

Do not paste any UTM URL into Google Ads. Use the plain final URL and let Google
auto-tagging append \`gclid\`/\`gbraid\`/\`wbraid\` — the site preserves them.
`;

// ── QR generation + independent decode verification ─────────────────────────
const qrPath = (name) => path.join(QR_DIR, name);

const generateQrFiles = async () => {
  fs.mkdirSync(QR_DIR, { recursive: true });
  for (const asset of qrAssets) {
    const url = linkUrl(byId.get(asset.linkId));
    const svg = await QRCode.toString(url, { ...QR_OPTS, type: 'svg', width: 1024 });
    fs.writeFileSync(qrPath(`${asset.id}.svg`), svg);
    await QRCode.toFile(qrPath(`${asset.id}.png`), url, { ...QR_OPTS, type: 'png', width: 1024 });
    await QRCode.toFile(qrPath(`${asset.id}-print.png`), url, { ...QR_OPTS, type: 'png', width: 3000 });
  }
};

const verifyQrFiles = async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext()).newPage();
  try {
    const sources = [
      'https://unpkg.com/jsqr@1.4.0/dist/jsQR.js',
      'https://cdn.jsdelivr.net/npm/jsqr@1.4.0/dist/jsQR.js',
    ];
    let loaded = false;
    for (const source of sources) {
      try {
        await page.addScriptTag({ url: source });
        loaded = true;
        break;
      } catch {
        /* try next source */
      }
    }
    if (!loaded) throw new Error('could not load the jsQR decoder from any CDN');

    const decode = (dataUrl, targetSize) =>
      page.evaluate(
        async ({ data, size }) => {
          const img = new Image();
          await new Promise((resolve, reject) => {
            img.onload = resolve;
            img.onerror = reject;
            img.src = data;
          });
          const canvas = document.createElement('canvas');
          canvas.width = size;
          canvas.height = size;
          const ctx = canvas.getContext('2d');
          ctx.drawImage(img, 0, 0, size, size);
          const image = ctx.getImageData(0, 0, size, size);
          const result = window.jsQR(image.data, size, size);
          return result ? result.data : null;
        },
        { data: dataUrl, size: targetSize },
      );

    const failures = [];
    for (const asset of qrAssets) {
      const expected = linkUrl(byId.get(asset.linkId));
      const svgPath = qrPath(`${asset.id}.svg`);
      const pngPath = qrPath(`${asset.id}.png`);
      const printPath = qrPath(`${asset.id}-print.png`);
      for (const file of [svgPath, pngPath, printPath]) {
        if (!fs.existsSync(file)) {
          failures.push(`${file} is missing`);
          continue;
        }
      }
      if (failures.length) continue;
      const decodeTargets = [
        [`data:image/svg+xml;base64,${fs.readFileSync(svgPath).toString('base64')}`, 1024, svgPath],
        [`data:image/png;base64,${fs.readFileSync(pngPath).toString('base64')}`, 1024, pngPath],
        [`data:image/png;base64,${fs.readFileSync(printPath).toString('base64')}`, 1000, printPath],
      ];
      for (const [dataUrl, size, file] of decodeTargets) {
        const decoded = await decode(dataUrl, size);
        if (decoded !== expected) {
          failures.push(`${file} decoded to "${decoded}" instead of "${expected}"`);
        }
      }
    }
    if (failures.length) {
      console.error('QR VERIFICATION FAILED:');
      for (const failure of failures) console.error(` - ${failure}`);
      process.exit(1);
    }
    console.log(`QR verification: ${qrAssets.length} codes × 3 files decoded — all EXACT MATCH`);
  } finally {
    await browser.close();
  }
};

// ── Run ──────────────────────────────────────────────────────────────────────
const writeIfChanged = (file, content) => {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) return false;
  if (!CHECK_ONLY) fs.writeFileSync(file, content);
  return true;
};

if (CHECK_ONLY) {
  const drifted = [
    [MASTER_MD, masterMd],
    [MASTER_CSV, masterCsv],
    [CHEAT_MD, cheatMd],
  ].filter(([file, content]) => fs.existsSync(file) && fs.readFileSync(file, 'utf8') !== content);
  const missing = [MASTER_MD, MASTER_CSV, CHEAT_MD].filter((file) => !fs.existsSync(file));
  if (missing.length || drifted.length) {
    console.error('DOCUMENT DRIFT DETECTED (run: npm run marketing:links):');
    for (const file of missing) console.error(` - missing ${file}`);
    for (const [file] of drifted) console.error(` - stale ${file}`);
    process.exit(1);
  }
  console.log('Marketing documents are up to date.');
} else {
  fs.mkdirSync(DOC_DIR, { recursive: true });
  writeIfChanged(MASTER_MD, masterMd);
  writeIfChanged(MASTER_CSV, masterCsv);
  writeIfChanged(CHEAT_MD, cheatMd);
  if (REGENERATE_QR) {
    await generateQrFiles();
  } else {
    fs.mkdirSync(QR_DIR, { recursive: true });
  }
  console.log(`Wrote ${MASTER_MD}, ${MASTER_CSV}, ${CHEAT_MD}`);
  console.log(
    `${marketingLinks.length} links across ${channelCount} channels · ${manualCount} owner manual steps · ${qrAssets.length} QR codes`,
  );
}

await verifyQrFiles();
